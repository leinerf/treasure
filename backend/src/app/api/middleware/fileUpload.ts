import multer from "multer";
import type { RequestHandler } from "express";
import path from "path";
import {config } from "../../../config.js";
import User from "../../../domain/models/user.js";
import fs from "fs";
import crypto from "node:crypto";

/**
 * Image types the disk upload accepts, mapped to the extension the server gives the file.
 * A Map, not an object literal, so a type like "constructor" can't match an inherited property.
 */
export const IMAGE_EXTENSIONS: ReadonlyMap<string, string> = new Map([
    ["image/jpeg", ".jpg"],
    ["image/png", ".png"],
    ["image/webp", ".webp"],
    ["image/gif", ".gif"],
]);

/**
 * Name for a stored upload, generated by the server. The client's filename is never used:
 * it could contain "../" and write outside the upload folder, or an extension such as .js
 * or .html that the static server would then serve from this origin.
 */
export const generateUploadFilename = (mimetype: string): string | null => {
    const extension = IMAGE_EXTENSIONS.get(mimetype);
    return extension ? `${Date.now()}-${crypto.randomUUID()}${extension}` : null;
};

/** Skips files that aren't an allowed image type; the route then sees no file and answers 400. */
export const imageFileFilter: multer.Options["fileFilter"] = (_req, file, cb) => {
    cb(null, IMAGE_EXTENSIONS.has(file.mimetype));
};

const appDir = path.dirname(path.dirname(import.meta.dirname))
const uploadDir = path.join(appDir, config.api_static_dir, config.api_img_dir);

const uploadToServerDest = (userId: string) => {
    const userUploadDir = path.join(uploadDir, userId);
        if(!fs.existsSync(userUploadDir)){
            fs.mkdirSync(userUploadDir, { recursive: true });
        }
    return userUploadDir;
};

const storage = multer.diskStorage({
    destination: (req, file, cb) => {
        const jwt = req.res?.locals.accessToken;
        const userId = User.jwtDecrypt(jwt);
        if(!userId){
            return cb(new Error("Invalid JWT"), "");
        }
        
        
        cb(null, uploadToServerDest(userId));
    },
    filename: (req, file, cb) => {
        const jwt = req.res?.locals.accessToken;
        const userId = User.jwtDecrypt(jwt);
        if(!userId){
            return cb(new Error("Invalid JWT"), "");
        }
        const filename = generateUploadFilename(file.mimetype);
        if(!filename){
            return cb(new Error("Unsupported file type"), "");
        }
        cb(null, filename);
    }
});

const memoryStorage = multer.memoryStorage();

/** Largest accepted upload. The S3 route holds the whole file in memory, so this also bounds memory use. */
export const MAX_UPLOAD_BYTES = 5 * 1024 * 1024;
const limits = { fileSize: MAX_UPLOAD_BYTES, files: 1 };

const upload = multer({ storage, fileFilter: imageFileFilter, limits });
const bufferUpload = multer({ storage: memoryStorage, limits });

/**
 * Runs a multer middleware and answers upload errors with JSON instead of passing them on.
 * These middlewares run before the route's error wrapper, so an unhandled MulterError would
 * reach Express's default handler and come back as a 500. multer removes any partly written
 * file before reporting the error.
 */
export const withUploadErrors = (middleware: RequestHandler): RequestHandler => (req, res, next) => {
    middleware(req, res, (error?: unknown) => {
        if (error instanceof multer.MulterError) {
            if (error.code === "LIMIT_FILE_SIZE") {
                return res.status(413).json({ error: `Image must be ${MAX_UPLOAD_BYTES / (1024 * 1024)} MB or smaller` });
            }
            return res.status(400).json({ error: "Upload one image in the \"profile\" field" });
        }
        next(error);
    });
};

/** Disk upload of one image, with a server-generated filename and the size limit. */
export const uploadSingleImage = (field: string): RequestHandler => withUploadErrors(upload.single(field));
/** In-memory upload of one file for S3, with the size limit. */
export const bufferUploadSingle = (field: string): RequestHandler => withUploadErrors(bufferUpload.single(field));

export default upload;
export {  bufferUpload };